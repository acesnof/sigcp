do $$ declare t text; begin
 foreach t in array array['utilizadores','app_settings','teams','welfares','team_membros','escala_loica','caixa_movimentos','day_offs','feriados','meses_trancados','sigcp_plus_meta','utilizadores_acessos','welfares_individuais','ferias','ferias_historico','ferias_notificacoes','sigcp_plus_recovery','auditoria'] loop
   execute format('drop policy if exists sigcp_read on public.%I', t);
   execute format('create policy sigcp_read on public.%I for select to anon, authenticated using (true)', t);
 end loop;
end $$;
